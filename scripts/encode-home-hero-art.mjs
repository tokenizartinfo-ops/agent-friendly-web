// One public, immutable illustration input; encoding happens only in GitHub.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import sharp from 'sharp';
assert.equal(process.env.GITHUB_ACTIONS,'true');
assert.equal(process.env.GITHUB_REPOSITORY,'tokenizartinfo-ops/agent-friendly-web');
const require=createRequire(import.meta.url);
assert.equal(require('sharp/package.json').version,'0.35.5');
const c=JSON.parse(await readFile('config/home-hero-art-20261027.json','utf8'));
assert.equal(c.repository,'tokenizartinfo-ops/agent-friendly-web');
assert.equal(c.blob,'99713003ef36dca2788680fee9aa276634acd5b2');
assert.equal(c.sha256,'28b1e584e05d97d1b9e71f35d38d80cf7cd4f9fe2f7a9e153e92cdca2f7b2fd5');
const r=await fetch('https://api.github.com/repos/tokenizartinfo-ops/agent-friendly-web/git/blobs/'+c.blob,{headers:{Accept:'application/vnd.github+json',Authorization:'Bearer '+process.env.GH_TOKEN},redirect:'manual',signal:AbortSignal.timeout(20000)});
assert.equal(r.status,200);const json=await r.json();
assert.equal(json.encoding,'base64');assert.equal(json.size,c.bytes);
const source=Buffer.from(json.content,'base64'),hash=b=>createHash('sha256').update(b).digest('hex');
assert.equal(source.length,c.bytes);assert.equal(hash(source),c.sha256);
assert.equal(source.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
assert.equal(source.readUInt32BE(16),1672);assert.equal(source.readUInt32BE(20),941);
const image=await sharp(source).webp({quality:82,effort:6}).toBuffer(),meta=await sharp(image).metadata();
assert.equal(meta.format,'webp');assert.equal(meta.width,1672);assert.equal(meta.height,941);
assert.ok(image.length>0&&image.length<450000,'mobile asset stays bounded');
await mkdir('output/home-hero-art',{recursive:true});
await writeFile('output/home-hero-art/agent-friendly-call-robots-screen.webp',image);
const receipt={source:c,bytes:image.length,sha256:hash(image),width:meta.width,height:meta.height,sourceRevision:process.env.AFW_QA_REVISION,runId:process.env.GITHUB_RUN_ID,published:false};
await writeFile('output/home-hero-art/receipt.json',JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify(receipt));
